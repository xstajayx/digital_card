export function jarIdeaBatch(theme, excluded, seen, previous = [], size = 4) {
  const available = (JAR_IDEAS[theme] ?? []).filter((idea) => !excluded.has(idea));
  const fresh = available.filter((idea) => !seen.has(idea));
  if (fresh.length >= size) return fresh.slice(0, size);
  const alternatives = available.filter((idea) => seen.has(idea) && !previous.includes(idea));
  const recent = available.filter((idea) => seen.has(idea) && previous.includes(idea));
  return [...fresh, ...alternatives, ...recent].slice(0, size);
}
